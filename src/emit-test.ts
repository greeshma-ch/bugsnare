import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import type { AgentResult } from "./agent/loop";
import type { AgentAction, Assertion } from "./actions";

function quote(value: string): string {
  return JSON.stringify(value) as string;
}

function singleLine(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

/**
 * Keeps a navigation on the target origin as a path so the generated spec uses
 * Playwright's `baseURL` instead of hard-coding a host.
 */
function navigationTarget(url: string, targetOrigin: string): string {
  let parsed: URL;
  try {
    parsed = new URL(url, targetOrigin);
  } catch {
    return url;
  }

  if (parsed.origin !== targetOrigin) return url;

  const path = `${parsed.pathname}${parsed.search}${parsed.hash}`;
  return path.length > 0 ? path : "/";
}

function renderAction(action: AgentAction, targetOrigin: string): string | undefined {
  switch (action.action) {
    case "goto":
      return `await page.goto(${quote(navigationTarget(action.url, targetOrigin))});`;
    case "click":
      return `await page.getByRole(${quote(action.role)}, { name: ${quote(action.name)} }).click();`;
    case "fill":
      return `await page.getByRole(${quote(action.role)}, { name: ${quote(action.name)} }).fill(${quote(action.value)});`;
    case "press":
      return `await page.keyboard.press(${quote(action.key)});`;
    case "assert_fail":
    case "give_up":
      return undefined;
  }
}

function locatorFor(assertion: Assertion): string {
  return assertion.name === undefined
    ? `page.getByRole(${quote(assertion.role)})`
    : `page.getByRole(${quote(assertion.role)}, { name: ${quote(assertion.name)} })`;
}

export function slugifyIssueTitle(title: string): string {
  const slug = singleLine(title)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");
  return slug.length > 0 ? slug : "bug";
}

/** Builds the standalone spec: replayed actions plus one behavioural assertion. */
export function renderSpec(result: AgentResult): string {
  const assertion = result.assertion;
  if (result.status !== "reproduced" || assertion === undefined) {
    throw new Error("emitTest needs a reproduced result with an assertion.");
  }

  const title = singleLine(result.issueTitle);
  const target = new URL(result.targetUrl);
  const targetOrigin = target.origin;
  const steps = result.trace
    .filter((entry) => entry.ok)
    .map((entry) => renderAction(entry.action, targetOrigin))
    .filter((line): line is string => line !== undefined);

  // The spec must start on the target page, even when the trace began there
  // already and never needed an explicit navigation.
  if (!steps.some((line) => line.startsWith("await page.goto("))) {
    steps.unshift(`await page.goto(${quote(target.pathname || "/")});`);
  }

  const body = [
    ...steps,
    `await expect(${locatorFor(assertion)}).toHaveText(${quote(assertion.expected)});`,
  ];

  return [
    "/**",
    ` * Generated by Bugsnare from issue: ${title.replace(/\*\//g, "* /")}`,
    " *",
    " * Replays the steps Bugsnare observed and asserts the expected behaviour,",
    " * so the test fails while the bug is still present. Contains no LLM code.",
    " */",
    'import { expect, test } from "@playwright/test";',
    "",
    `test(${quote(title)}, async ({ page }) => {`,
    ...body.map((line) => `  ${line}`),
    "});",
    "",
  ].join("\n");
}

/** Writes a runnable Playwright spec and returns its source. */
export async function emitTest(result: AgentResult, outPath: string): Promise<string> {
  const source = renderSpec(result);
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, source, "utf8");
  return source;
}